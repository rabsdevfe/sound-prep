// Generates the desktop side of the IPC contract from contracts/ipc.schema.json:
//   src/ipc/types.generated.ts      TypeScript types (json-schema-to-typescript)
//   src/ipc/validate.generated.js   precompiled Ajv validator (no eval at runtime, CSP-safe)
// Usage: node scripts/generate-ipc.mjs [--check]   (--check fails when files are stale)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import process from "node:process";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const root = new URL("../", import.meta.url);
const schemaPath = new URL("../../contracts/ipc.schema.json", root);
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));

const banner = "Generated by scripts/generate-ipc.mjs from contracts/ipc.schema.json. Do not edit.";

const ajv = new Ajv2020({
  strict: true,
  allErrors: true,
  code: { source: true, esm: true },
});
const validate = ajv.compile(schema);
// Ajv's ESM output still emits a CommonJS require for its code point counter, which does not
// interop reliably as an ES import; inline an equivalent (code points, as in Python's len()).
const helper = /const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g;
let body = standaloneCode(ajv, validate);
body = body.replace(helper, (_, name) => `const ${name} = (s) => [...s].length;`);
if (body.includes("require(")) {
  throw new Error("standalone validator still contains require(); extend the helper rewrite");
}
const validatorSource = `// ${banner}\n// @ts-nocheck\n${body}`;

// The schema discriminates on `type` with if/then, which yields no useful TS union; type the union of
// the four message definitions instead.
const refs = Object.keys(schema.$defs).filter((n) => /(Request|Event|Message)$/.test(n));
const typeSchema = {
  title: "IpcMessage",
  description: schema.description,
  oneOf: refs.map((n) => ({ $ref: `#/$defs/${n}` })),
  $defs: schema.$defs,
};
const typesSource = await compile(typeSchema, "IpcMessage", {
  bannerComment: `/* ${banner} */`,
  additionalProperties: false,
  format: false,
});

const outputs = [
  ["src/ipc/validate.generated.ts", validatorSource],
  ["src/ipc/types.generated.ts", typesSource],
];

const check = process.argv.includes("--check");
let stale = false;
for (const [rel, content] of outputs) {
  const path = fileURLToPath(new URL(rel, root));
  if (check) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
      console.error(`stale: ${rel} (run \`npm run generate:ipc\`)`);
      stale = true;
    }
  } else {
    writeFileSync(path, content);
  }
}
process.exit(stale ? 1 : 0);
